export function translate(
  text: string,
  locale: UiLocale,
  vars?: Record<string, string | number>,
): string {
  let out = locale === "es" ? text : EN[text] ?? text;
  if (vars) {
    for (const [key, value] of Object.entries(vars)) {
      out = out.replaceAll(`{${key}}`, String(value));
    }
  }
  return out;
}

type I18nValue = {
  locale: UiLocale;
  setLocale: (locale: UiLocale) => void;
  t: (text: string, vars?: Record<string, string | number>) => string;
};

const I18nContext = React.createContext<I18nValue>({
  locale: "en",
  setLocale: () => {},
  t: (text) => text,
});

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = React.useState<UiLocale>("en");
  activeLocale = locale;

  React.useEffect(() => {
    try {
      const saved = window.localStorage.getItem("capturas:ui-locale");
      if (saved === "es" || saved === "en") setLocaleState(saved);
    } catch {
      // Storage unavailable: English remains.
    }
  }, []);

  React.useEffect(() => {
    document.documentElement.lang = locale;
    try {
      window.localStorage.setItem("capturas:ui-locale", locale);
    } catch {
      // Ignore storage failures.
    }
    window.electronAPI?.setUiLocale?.(locale);
  }, [locale]);

  const setLocale = React.useCallback((next: UiLocale) => setLocaleState(next), []);
  const t = React.useCallback(
    (text: string, vars?: Record<string, string | number>) => translate(text, locale, vars),
    [locale],
  );
  const value = React.useMemo(() => ({ locale, setLocale, t }), [locale, setLocale, t]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export const useI18n = () => React.useContext(I18nContext);
