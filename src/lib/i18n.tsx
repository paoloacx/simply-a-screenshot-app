let activeLocale: UiLocale = "en";

/** Locale for code that cannot call the hook (helpers, dialogs rendered in portals). */
export function setActiveLocale(locale: UiLocale) {
  activeLocale = locale;
}

/** Translate with the currently active locale. Components using the provider re-render on change. */
export function t(text: string, vars?: Record<string, string | number>): string {
  return translate(text, activeLocale, vars);
}

